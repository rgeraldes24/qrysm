package main

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/theQRL/qrysm/testing/require"
)

func TestStagePbgo(t *testing.T) {
	t.Run("copies .pb.go files, skipping minimal twins and other files", func(t *testing.T) {
		dir := t.TempDir()
		writeRepoFile(t, dir, "pkg/foo.pb.go", "package foo\n")
		writeRepoFile(t, dir, "pkg/bar.pb.go", "package bar\n")
		writeRepoFile(t, dir, "pkg/baz.minimal.pb.go", "package baz\n")
		writeRepoFile(t, dir, "pkg/foo.pb.gw.go", "package foo\n")
		writeRepoFile(t, dir, "pkg/generated.ssz.go", "package foo\n")
		writeRepoFile(t, dir, "pkg/sub.pb.go/x", "")

		stageDir := filepath.Join(dir, "stage")
		require.NoError(t, stagePbgo(filepath.Join(dir, "pkg"), stageDir))

		entries, err := os.ReadDir(stageDir)
		require.NoError(t, err)
		var names []string
		for _, e := range entries {
			names = append(names, e.Name())
		}
		require.DeepEqual(t, []string{"bar.pb.go", "foo.pb.go"}, names)

		got, err := os.ReadFile(filepath.Join(stageDir, "foo.pb.go"))
		require.NoError(t, err)
		require.Equal(t, "package foo\n", string(got))
	})

	t.Run("errors when the package dir cannot be read", func(t *testing.T) {
		dir := t.TempDir()
		err := stagePbgo(filepath.Join(dir, "missing"), filepath.Join(dir, "stage"))
		require.ErrorContains(t, "readDir:", err)
	})
}

func TestStripHashLine(t *testing.T) {
	in := "// Code generated by fastssz. DO NOT EDIT.\n// Hash: 0123\npackage v1\n\n\t// Hash: indented, kept\n"
	want := "// Code generated by fastssz. DO NOT EDIT.\npackage v1\n\n\t// Hash: indented, kept\n"
	require.Equal(t, want, stripHashLine(in))
}
